// Sun / moon toggle for the colour theme.
function ThemeToggle({ theme, onToggle }) {
  const dark = theme === 'dark'
  return (
    <button
      type="button"
      className="theme-toggle"
      onClick={onToggle}
      aria-label={dark ? 'Switch to light mode' : 'Switch to dark mode'}
      title={dark ? 'Light mode' : 'Dark mode'}
    >
      {dark ? (
        // sun
        <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
          <circle cx="12" cy="12" r="4" />
          <path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4" />
        </svg>
      ) : (
        // moon
        <svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
          <path d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8z" />
        </svg>
      )}
    </button>
  )
}

// Small balance indicator in the header. Hidden until the account loads so it
// never flashes a wrong number.
function CreditPill() {
  const { account } = useAuth()
  if (!account || !account.verified) return null
  const empty = account.balance < 1
  return (
    <a className={`credit-pill ${empty ? 'is-empty' : ''}`} href="#/pricing" title="Credits remaining">
      <span className="credit-pill-num">{account.balance}</span>
      <span className="credit-pill-label">{account.balance === 1 ? 'credit' : 'credits'}</span>
    </a>
  )
}

// Sign in / sign out control in the header.
function AccountControl() {
  const { account, loading, signOut } = useAuth()
  if (loading) return null

  if (!account) {
    return (
      <span className="auth-links">
        <a className="site-nav-link" href="#/login">Sign in</a>
        <a className="btn btn-primary site-nav-cta" href="#/signup">Create account</a>
      </span>
    )
  }

  return (
    <span className="auth-links">
      <a className="site-nav-link" href="#/drafts">My drafts</a>
      <span className="account-email" title={account.email}>{account.email}</span>
      <button type="button" className="linklike" onClick={signOut}>Sign out</button>
    </span>
  )
}

function SiteHeader({ path, theme, onToggleTheme }) {
  const [open, setOpen] = useState(false)

  // Close the mobile menu whenever the route changes.
  useEffect(() => {
    setOpen(false)
  }, [path])

  return (
    <header className="site-header">
      <div className="site-container site-header-inner">
        <Logo />

        <nav className={`site-nav ${open ? 'is-open' : ''}`}>
          {NAV.map((item) => (
            <a
              key={item.path}
              href={`#${item.path}`}
              className={`site-nav-link ${path === item.path ? 'is-active' : ''}`}
            >
              {item.en} <span className="site-nav-ur">{item.ur}</span>
            </a>
          ))}
          <CreditPill />
          <AccountControl />
        </nav>

        <div className="site-header-controls">
          <ThemeToggle theme={theme} onToggle={onToggleTheme} />
          <button
            type="button"
            className="site-menu-btn"
            aria-label="Toggle menu"
            aria-expanded={open}
            onClick={() => setOpen((v) => !v)}
          >
            <span />
            <span />
            <span />
          </button>
        </div>
      </div>
    </header>
  )
}

