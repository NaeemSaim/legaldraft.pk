// ---------------------------------------------------------------------------
// Colour theme (light / dark)
// ---------------------------------------------------------------------------
// The theme follows the device/system setting by default, but the user can
// override it with the header toggle. Their choice is saved in localStorage so
// it sticks across visits. The initial value is set by a small inline script
// in index.html (which also prevents a flash of the wrong theme on load); the
// code below keeps React in step and handles the toggle and system changes.
// ---------------------------------------------------------------------------

const THEME_KEY = 'legaldraft_theme'

function readStoredTheme() {
  try {
    const v = window.localStorage.getItem(THEME_KEY)
    if (v === 'light' || v === 'dark') return v
  } catch {
    /* private browsing */
  }
  return null
}

function systemPrefersDark() {
  return Boolean(window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches)
}

function initialTheme() {
  // Trust whatever the inline script already put on <html>, then fall back.
  const attr = document.documentElement.getAttribute('data-theme')
  if (attr === 'light' || attr === 'dark') return attr
  return readStoredTheme() || (systemPrefersDark() ? 'dark' : 'light')
}

