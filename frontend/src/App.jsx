export default function App() {
  const [path, setPath] = useState(currentPath())
  const [theme, setTheme] = useState(initialTheme)

  useEffect(() => {
    const onChange = () => {
      setPath(currentPath())
      window.scrollTo(0, 0)
    }
    window.addEventListener('hashchange', onChange)
    return () => window.removeEventListener('hashchange', onChange)
  }, [])

  // Keep the <html data-theme> attribute in step with our state.
  useEffect(() => {
    document.documentElement.setAttribute('data-theme', theme)
  }, [theme])

  // Follow the system setting live — but only while the user has NOT made an
  // explicit choice with the toggle.
  useEffect(() => {
    if (!window.matchMedia) return
    const mq = window.matchMedia('(prefers-color-scheme: dark)')
    const onChange = (e) => {
      if (!readStoredTheme()) setTheme(e.matches ? 'dark' : 'light')
    }
    if (mq.addEventListener) mq.addEventListener('change', onChange)
    else mq.addListener(onChange)
    return () => {
      if (mq.removeEventListener) mq.removeEventListener('change', onChange)
      else mq.removeListener(onChange)
    }
  }, [])

  const toggleTheme = useCallback(() => {
    setTheme((t) => {
      const next = t === 'dark' ? 'light' : 'dark'
      try {
        window.localStorage.setItem(THEME_KEY, next)
      } catch {
        /* private browsing — the choice just won't persist */
      }
      return next
    })
  }, [])

  const Page = ROUTES[path] || Landing
  // The drafting tool manages its own wide layout; static pages sit in a
  // narrower reading column (handled in CSS via .site-main-tool).
  const isTool = path === '/draft'

  return (
    <AuthProvider>
      <div className="site">
        <SiteHeader path={path} theme={theme} onToggleTheme={toggleTheme} />
        <main className={isTool ? 'site-main site-main-tool' : 'site-main'}>
          <Page />
        </main>
        <SiteFooter />
      </div>
    </AuthProvider>
  )
}
